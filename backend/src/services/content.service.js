export class ContentService {
  /** Жаңартуды тексеру — қосымша нұсқаны салыстырады. */
  static manifest() {
    let moduleCount = 0;
    for (const subject of Object.values(MODULE_TITLES)) {
      for (const grade of Object.values(subject)) moduleCount += grade.length;
    }
    return {
      version: CONTENT_VERSION,
      subjects: Object.keys(MODULE_TITLES),
      subject_count: Object.keys(MODULE_TITLES).length,
      grade_range: [5, 11],
      module_count: moduleCount,
      generated_at: new Date().toISOString(),
    };
  }

  /** Толық таксономия (пән → сынып → модуль атаулары). */
  static curriculum() {
    return {
      version: CONTENT_VERSION,
      subjects: Object.entries(SUBJECT_META).map(([id, meta]) => ({
        id,
        ...meta,
        grades: MODULE_TITLES[id],
      })),
    };
  }

  /** Бір пәннің құрылымы. */
  static subject(id) {
    if (!MODULE_TITLES[id]) return null;
    return { id, ...SUBJECT_META[id], grades: MODULE_TITLES[id] };
  }
}

export default ContentService;
