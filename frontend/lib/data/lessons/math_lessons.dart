/// Берілген пән/сынып/модульдің сабағы (жоқ болса — null).
/// 5–6 сынып — mathLessons, 7–11 сынып — mathLessonsSenior.
Lesson? lessonFor(String subject, int grade, int module) {
  switch (subject) {
    case 'math':
      return mathLessons[grade]?[module] ?? mathLessonsSenior[grade]?[module];
    case 'kazakh':
      return kazakhLessons[grade]?[module];
    case 'english':
      return englishLessons[grade]?[module];
    case 'physics':
      return physicsLessons[grade]?[module];
    case 'cs':
      return csLessons[grade]?[module];
    case 'biology':
      return biologyLessons[grade]?[module];
    case 'chemistry':
      return chemistryLessons[grade]?[module];
    case 'history':
      return historyLessons[grade]?[module];
    default:
      return null;
  }
}

/// Барлық сабақтар (іздеу үшін біріктірілген тізім).
Iterable<Lesson> get allLessons sync* {
  for (final map in [
    mathLessons,
    mathLessonsSenior,
    kazakhLessons,
    englishLessons,
    physicsLessons,
    csLessons,
    biologyLessons,
    chemistryLessons,
    historyLessons,
  ]) {
    for (final grade in map.values) {
      yield* grade.values;
    }
  }
}

/// Екі сөз ТҮБІРЛЕС пе (ортақ префикс ≥5 әріп). Қазақ жалғаулы тіл болғандықтан
/// «бөлшек/бөлшекті/бөлшектер», «септік/септігі», «теңдеу/теңдеулер» сәйкес
/// келуі үшін толық сәйкестік емес, түбір сәйкестігі қажет.
bool _stemMatch(String a, String b) {
  final n = a.length < b.length ? a.length : b.length;
  if (n < 5) return a == b;
  var i = 0;
  while (i < n && a[i] == b[i]) {
    i++;
  }
  return i >= 5;
}

List<String> _topicWords(String s, int minLen) => s
    .toLowerCase()
    .split(RegExp(r'[\s,.:;()«»?!"–—]+'))
    .where((w) => w.length >= minLen)
    .toList();

/// Сұрақтан тақырыпқа сай сабақты табу (офлайн ассистент НАҚТЫ түсіндіру үшін).
/// Сұрақ сөзінің ТҮБІРІ сабақ тақырыбымен сәйкес келсе — сол сабақ; әйтпесе
/// (кемі 2 интро сөзі сәйкес) сабақ интросынан. Сәйкес болмаса — null (ассистент
/// ойдан жауап ШЫҒАРМАЙДЫ, адал «білмеймін» дейді).
Lesson? findLessonByTopic(String query) {
  final qWords = _topicWords(query, 4);
  if (qWords.isEmpty) return null;
  Lesson? best;
  var bestScore = 0;
  for (final lesson in allLessons) {
    final titleWords = _topicWords(lesson.title, 4);
    // Интро қысқа «негізгі идея» болғандықтан, іздеу қадамдық түсіндірмені де
    // қамтиды. hook ӘДЕЙІ қосылмайды: өмірлік әңгімедегі тақырыптан тыс сөздер
    // (пицца, дүкен, ғарышкер…) жалған сәйкестік туғызады — ассистент білмеген
    // тақырыпқа адал «білмеймін» деуі керек.
    final introWords = _topicWords(
      '${lesson.intro} ${lesson.explainSteps.join(' ')}',
      5,
    );
    var titleHits = 0;
    var introHits = 0;
    for (final qw in qWords) {
      if (titleWords.any((tw) => _stemMatch(qw, tw))) {
        titleHits++;
      } else if (introWords.any((iw) => _stemMatch(qw, iw))) {
        introHits++;
      }
    }
    final score = titleHits * 3 + introHits;
    final qualifies = titleHits >= 1 || introHits >= 2;
    if (qualifies && score > bestScore) {
      bestScore = score;
      best = lesson;
    }
  }
  return best;
}
