Question kazakhGenQuestion(
    String id, int grade, Random r, Difficulty difficulty) {
  final list = switch (difficulty) {
    Difficulty.light => _plural,
    Difficulty.easy => _cases,
    Difficulty.medium => _pos,
    Difficulty.hard => _antonym,
    Difficulty.complex => _root,
    Difficulty.brainTeaser => _proverb,
  };
  final e = list[r.nextInt(list.length)];
  final opts = <String>[e.$2];
  for (final w in e.$3) {
    if (opts.length >= 4) break;
    if (!opts.contains(w)) opts.add(w);
  }
  opts.shuffle(r);
  return Question(
    id: id,
    text: e.$1,
    options: opts,
    correctIndex: opts.indexOf(e.$2),
    hint: null,
    difficulty: difficulty,
  );
}
